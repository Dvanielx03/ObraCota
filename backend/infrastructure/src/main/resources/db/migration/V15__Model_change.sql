-- Generalised design change: recipe of typed operations over a base version.
create table model_change (
  id uuid primary key,
  project_id uuid not null references project(id) on delete cascade,
  file_id uuid not null references model_file(id) on delete cascade,
  base_version uuid not null references model_version(id) on delete cascade,
  format varchar(3) not null,
  status varchar(10) not null,
  origin varchar(6) not null,
  author_id uuid not null references security_user(id),
  agent_run_id uuid,
  description varchar(2000) not null,
  summary varchar(2000),
  recipe text not null,
  report text,
  report_recipe_sha256 varchar(64),
  previewed_at timestamp with time zone,
  preview_id uuid,
  preview_sha256 varchar(64),
  preview_size bigint,
  legacy_review text,
  picture bytea,
  submitted_at timestamp with time zone,
  applied_version uuid references model_version(id) on delete set null,
  applied_at timestamp with time zone,
  applied_by uuid references security_user(id),
  approved_estimate text,
  restored_version uuid references model_version(id) on delete set null,
  restored_at timestamp with time zone,
  restored_by uuid references security_user(id),
  discarded_at timestamp with time zone,
  discarded_by uuid references security_user(id),
  discarded_by_kind varchar(6),
  created_at timestamp with time zone not null,
  updated_at timestamp with time zone not null,
  constraint ck_model_change_format check (format in ('IFC','DWG')),
  constraint ck_model_change_status check (status in ('DRAFT','READY','APPLIED','RESTORED','DISCARDED')),
  constraint ck_model_change_origin check (origin in ('PERSON','AGENT')),
  constraint ck_model_change_agent check ((origin = 'AGENT') = (agent_run_id is not null)),
  constraint ck_model_change_applied check (status not in ('APPLIED','RESTORED') or applied_at is not null),
  constraint ck_model_change_restored check (status <> 'RESTORED' or restored_at is not null),
  constraint ck_model_change_discarded check ((status = 'DISCARDED') = (discarded_at is not null)),
  constraint ck_model_change_discarded_kind check (((status = 'DISCARDED') = (discarded_by_kind is not null))
    and (discarded_by_kind is null or discarded_by_kind in ('PERSON','AGENT'))),
  constraint ck_model_change_preview check ((preview_sha256 is null) = (preview_size is null)
    and (preview_sha256 is null) = (preview_id is null))
);
create index ix_model_change_project on model_change(project_id, created_at);
create index ix_model_change_status on model_change(project_id, status);
create index ix_model_change_base on model_change(base_version);

-- Audit trail: who did what and when (who approved, who restored).
create table model_change_event (
  id bigint generated by default as identity primary key,
  change_id uuid not null references model_change(id) on delete cascade,
  action varchar(20) not null,
  actor_kind varchar(8) not null,
  actor_user uuid references security_user(id),
  agent_run_id uuid,
  detail varchar(2000),
  created_at timestamp with time zone not null,
  constraint ck_model_change_event_actor check (actor_kind in ('PERSON','AGENT','SYSTEM'))
);
create index ix_model_change_event on model_change_event(change_id, created_at);

-- Unit prices per version, generalised from door_unit_price (key, unit, currency, copy origin).
create table unit_price (
  project_id uuid not null references project(id) on delete cascade,
  version_id uuid not null references model_version(id) on delete cascade,
  price_key varchar(80) not null,
  unit varchar(8) not null,
  currency varchar(3) not null,
  amount decimal(18,2) not null,
  source varchar(300) not null,
  price_date date not null,
  copied_from uuid references model_version(id) on delete set null,
  updated_at timestamp with time zone not null,
  primary key (project_id, version_id, price_key),
  constraint ck_unit_price_unit check (unit in ('UNIT','M','M2','M3')),
  constraint ck_unit_price_amount check (amount >= 0)
);

-- Agent tool journal (written from H4 on). run_id has no FK, like ai_run.batch_id.
create table agent_tool_call (
  id bigint generated by default as identity primary key,
  run_id uuid not null,
  step integer not null,
  seq integer not null,
  project_id uuid not null references project(id) on delete cascade,
  user_id uuid not null references security_user(id),
  change_id uuid references model_change(id) on delete set null,
  tool varchar(64) not null,
  arguments text not null,
  result text,
  status varchar(10) not null,
  error_code varchar(80),
  duration_ms integer,
  created_at timestamp with time zone not null,
  constraint uq_agent_tool_call unique (run_id, step, seq),
  constraint ck_agent_tool_call_status check (status in ('OK','REJECTED','ERROR'))
);
create index ix_agent_tool_call_change on agent_tool_call(change_id);

-- History: door_change -> model_change, keeping ids (the #id anchors keep working).
insert into model_change (id, project_id, file_id, base_version, format, status, origin, author_id, agent_run_id,
  description, summary, recipe, report, report_recipe_sha256, previewed_at, preview_id, preview_sha256, preview_size,
  legacy_review, picture, submitted_at, applied_version, applied_at, applied_by, approved_estimate,
  restored_version, restored_at, restored_by, discarded_at, discarded_by, discarded_by_kind, created_at, updated_at)
select d.id, d.project_id, b.file_id, d.base_version, 'IFC',
  -- Pending changes have no verified preview: they come back as drafts (DRAFT), never as READY.
  case when d.restored_version is not null then 'RESTORED' when d.applied_at is not null then 'APPLIED' else 'DRAFT' end,
  'PERSON', d.author_id, null, d.description, null,
  '{"format":"obracota.recipe/1","operations":[{"id":"op-1","op":"ifc.change_type","element":"' || d.element_key
    || '","type_id":"' || d.type_key || '"}]}',
  null, null, null, null, null, null,
  d.review, d.picture, case when d.applied_at is not null then d.created_at end,
  d.applied_version, d.applied_at, a.uploaded_by, null,
  d.restored_version, r.uploaded_at, r.uploaded_by, null, null, null,
  d.created_at, coalesce(r.uploaded_at, d.applied_at, d.created_at)
from door_change d
join model_version b on b.id = d.base_version
left join model_version a on a.id = d.applied_version
left join model_version r on r.id = d.restored_version;

insert into model_change_event (change_id, action, actor_kind, actor_user, agent_run_id, detail, created_at)
select id, 'CREATE', 'PERSON', author_id, null, 'Migrado desde door_change (V15).', created_at from model_change;
insert into model_change_event (change_id, action, actor_kind, actor_user, agent_run_id, detail, created_at)
select id, 'APPLY', 'PERSON', applied_by, null, 'Migrado: la persona sale de quien subió la versión aplicada.', applied_at
from model_change where applied_at is not null;
insert into model_change_event (change_id, action, actor_kind, actor_user, agent_run_id, detail, created_at)
select id, 'RESTORE', 'PERSON', restored_by, null, 'Migrado: la persona y la fecha salen de la versión restaurada.', restored_at
from model_change where restored_at is not null;

insert into unit_price (project_id, version_id, price_key, unit, currency, amount, source, price_date, copied_from, updated_at)
select project_id, version_id, 'type:' || type_key, 'UNIT', 'COP', amount, source, price_date, null, current_timestamp
from door_unit_price;

