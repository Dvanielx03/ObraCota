package com.obracota.application.designoption.usecase;

import com.obracota.application.airun.usecase.AiBudget;
import com.obracota.application.common.exception.ConflictApplicationException;
import com.obracota.application.common.exception.NotFoundApplicationException;
import com.obracota.application.common.port.Transactions;
import com.obracota.application.designoption.port.DesignOptionBatches;
import com.obracota.application.designoption.port.DesignOptionBatches.Binary;
import com.obracota.application.designoption.port.DesignOptionBatches.NewBatch;
import com.obracota.application.modelversion.usecase.ProjectVersions;
import java.util.List;
import java.util.Map;
import java.util.UUID;

/**
 * Visual options of an element: a batch of three generated by the worker, paid from the monthly AI budget. The budget is
 * reserved in the same transaction that queues the batch, so a batch never exists without its reservation.
 */
public final class DesignOptions {
    /** Cents reserved from the monthly budget by each batch of three options with a paid image provider. */
    public static final int RESERVE_CENTS = 100;
    public static final String INCOMPLETE = "La terna aún no está completa.";

    private final ProjectVersions versions;
    private final DesignOptionBatches batches;
    private final AiBudget budget;
    private final Transactions tx;
    private final int reserveCents;

    public DesignOptions(ProjectVersions versions, DesignOptionBatches batches, AiBudget budget, Transactions tx) {
        this(versions, batches, budget, tx, RESERVE_CENTS);
    }

    /** {@code reserveCents} is 0 when images come from a free provider, so free batches do not spend the monthly budget. */
    public DesignOptions(ProjectVersions versions, DesignOptionBatches batches, AiBudget budget, Transactions tx, int reserveCents) {
        this.versions = versions;
        this.batches = batches;
        this.budget = budget;
        this.tx = tx;
        this.reserveCents = reserveCents;
    }

    public int reserveCents() { return reserveCents; }

    public record Listing(List<Map<String, Object>> batches, int remainingCents) {}

    public Listing list(UUID project, UUID version, UUID user, String element) {
        return tx.required(() -> {
            versions.get(project, user, version);
            return new Listing(batches.list(version, element), budget.remaining());
        });
    }

    /**
     * Queues the batch and reserves {@link #RESERVE_CENTS}. A retry of the same batch returns without reserving again.
     *
     * @throws AiBudget.Exhausted when the month has no room for the batch
     */
    public UUID submit(UUID project, UUID user, NewBatch batch) {
        return tx.required(() -> {
            versions.get(project, user, batch.version());
            budget.lock();
            if (batches.exists(batch.id(), batch.version(), user, batch.element(), batch.request())) return batch.id();
            if (reserveCents > 0) budget.reserve(reserveCents);
            batches.queue(new NewBatch(batch.id(), batch.version(), user, batch.element(), batch.name(), batch.request(),
                batch.captured(), batch.mask()));
            return batch.id();
        });
    }

    /** Slot 0 is the captured screenshot; 1 to 3 are the generated options. */
    public Binary image(UUID project, UUID version, UUID user, UUID id, int slot) {
        return tx.required(() -> {
            within(project, version, user, id);
            var image = slot == 0 ? batches.captured(id) : batches.image(id, slot);
            return image.orElseThrow(NotFoundApplicationException::new);
        });
    }

    public void select(UUID project, UUID version, UUID user, UUID id, int slot) {
        tx.required(() -> {
            within(project, version, user, id);
            if (slot < 1 || slot > 3 || !batches.select(id, slot)) throw new ConflictApplicationException(INCOMPLETE);
            return null;
        });
    }

    private void within(UUID project, UUID version, UUID user, UUID id) {
        versions.get(project, user, version);
        if (!batches.belongs(version, id)) throw new NotFoundApplicationException();
    }
}
